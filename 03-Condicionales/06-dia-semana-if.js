// DÍA DE LA SEMANA UTILIZANDO IF

let dia = 3;

if (dia === 1) {
  console.log("Lunes");
} else if (dia === 2) {
  console.log("Martes");
} else if (dia === 3) {
  console.log("Miércoles");
} else if (dia === 4) {
  console.log("Jueves");
} else if (dia === 5) {
  console.log("Viernes");
} else {
  console.log("Día incorrecto");
}

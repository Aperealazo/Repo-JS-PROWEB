// EJEMPLO: MENÚ UTILIZANDO SWITCH

let opcion = 2;

switch (opcion) {

  case 1:
    console.log("Agregar producto");
    break;

  case 2:
    console.log("Modificar producto");
    break;

  case 3:
    console.log("Eliminar producto");
    break;

  case 4:
    console.log("Salir");
    break;

  default:
    console.log("Opción incorrecta");
}

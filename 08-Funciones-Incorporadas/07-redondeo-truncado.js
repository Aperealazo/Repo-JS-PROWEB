// REDONDEO Y TRUNCADO

let promedio = 7.8;

console.log("Número original:");
console.log(promedio);

// Redondea al número más cercano
console.log("Math.round:");
console.log(Math.round(promedio));

// Redondea hacia abajo
console.log("Math.floor:");
console.log(Math.floor(promedio));

// Redondea hacia arriba
console.log("Math.ceil:");
console.log(Math.ceil(promedio));

// Elimina los decimales
console.log("Math.trunc:");
console.log(Math.trunc(promedio));
